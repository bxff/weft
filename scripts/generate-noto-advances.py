#!/usr/bin/env python3
"""Regenerate the layout advances from Weft's bundled, OFL-licensed Noto faces."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
fonts = root / "apps/web/static/fonts/rm"
target = root / "apps/web/src/lib/tldraw/noto-font-advances.ts"
faces = {
    "sansRegular": "NotoSans-Regular",
    "sansBold": "NotoSans-Bold",
    "sansItalic": "NotoSans-Italic",
    "serifSmall": "NotoSerif-Regular",
    "serifSmallBold": "NotoSerif-Bold",
}
data = {}
for key, stem in faces.items():
    with TTFont(fonts / f"{stem}.ttf") as font:
        upm = font["head"].unitsPerEm
        hmtx = font["hmtx"].metrics
        data[key] = {
            chr(code): hmtx[glyph][0] / upm
            for code, glyph in sorted(font.getBestCmap().items())
        }
data["sansMedium"] = data["sansRegular"]
target.write_text(
    "// Generated by scripts/generate-noto-advances.py from bundled Noto fonts.\n"
    "export const OPEN_FONT_ADVANCES: Record<string, Record<string, number>> = "
    + json.dumps(data, ensure_ascii=True, separators=(",", ":"))
    + "\n",
    encoding="utf-8",
)
